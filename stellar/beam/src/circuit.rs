pub(crate) const PROOF_LEN: u32 = 256 + 32;

fn field(env: &Env, bytes: &BytesN<32>) -> U256 {
    U256::from_be_bytes(env, &Bytes::from_slice(env, &bytes.to_array()))
}

pub(crate) fn extract(env: &Env, proof: &Bytes) -> Option<(Bytes, U256)> {
    if proof.len() != PROOF_LEN {
        return None;
    }
    let nullifier: BytesN<32> = proof.slice(256..PROOF_LEN).try_into().unwrap();
    Some((proof.slice(0..256), field(env, &nullifier)))
}

